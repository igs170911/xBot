// Package replystyle 是 Bot 講話長短與先後順序的唯一來源。
//
// 2026-10-23 使用者：「回應沒有這麼穠纖合度，現在有點太短，之前有點太長」「好像一直都在瞎忙」。原本長度的規定散在十幾處、
// 數字各說各話（一兩句、三到五句、兩段、短短幾段、兩三行、八行、十行…），而附在你每則訊息後面的「三到五句」蓋過其他規定，
// 連要研究、要規劃的事也只回幾句。現在守則（SOUL）、你打的訊息後面的提醒（OwnerNote）、隊友傳話、群組、自動續做、團隊
// 都從這裡拿。長短看使用者要拿這則訊息做什麼，不看 Bot 做了多少事。
//
// 寫成白話、一行一件事、不用清單符號和粗體：提示的格式會被模型照抄到回覆裡。
package replystyle

// Head 是守則裡「回話長度」段落的標題。
const Head = "## 回話長度"

// simple 是簡單問題的長度，跟著回話風格設定（設定 › 一般 › 回話風格；hermes.ReplyStyle 的值）。
// 簡短（預設）的三到五句是使用者 2026-10-21 確認過的。
var simple = map[string]string{
	"brief":    "三到五句、兩段內",
	"normal":   "兩到四段，每段兩三句",
	"detailed": "可以完整說明，每段一件事",
}

// Length 是守則的「回話長度」段落。style 是回話風格（brief、normal、detailed；不認得的照 brief）。
func Length(style string) string {
	s := simple[style]
	if s == "" {
		s = simple["brief"]
	}
	return Head + "\n" +
		"長短看使用者要拿這則訊息做什麼，不看你做了多少事：\n" +
		"閒聊、打招呼：一兩句。\n" +
		"簡單問題、問事實：第一句就是答案，" + s + "；要出處的附連結。\n" +
		"問建議、要你比較：先說你選哪個、為什麼，其他選項一兩句帶過，合起來" + s + "。\n" +
		"要你研究、調查、規劃、設計：先真的查過幾個來源再回。對話裡給結論和骨架（誰做什麼、先後順序、關鍵數字），一個手機畫面看得完；" +
		"細節和來源寫成檔案、給路徑。沒查過不要說研究過。\n" +
		"交代的工作做完：一句說好了沒、東西在哪，再補沒做到的或有風險的；不寫過程。\n" +
		"問進度、問東西在哪：一兩句，說做到哪、卡在哪、還要多久，或給路徑；不要把成品整份貼出來。\n" +
		Order + PeerResult + "\n" + Teamwork + "\n"
}

// Order 是講話的先後（回給使用者的都適用）。
const Order = "要他決定、提供或去做的事：回覆只有一兩段時放在最後一句；比較長的就放第一段，一題一段、附選項和你的建議，不要埋在最後。\n" +
	"能自己決定、做得到的就直接做完，再說一句做了什麼；不要做一步就問「要我…嗎」。只有花錢、對外發送、刪除，或有幾條路而選錯很難回頭時才先問。\n" +
	"做完不要在結尾問要不要再做別的（「要我…嗎」「需要的話…」）；真的值得做的下一步，一句話直說你建議什麼。\n"

// PeerResult 是交回給主管或隊友的長度（最後回答會送回隊友時；不照給使用者的分段）。
const PeerResult = "交回給主管或隊友：結論、關鍵數字、檔案路徑，十行內；不重述交辦內容、不寫客套，長的資料存成檔案給路徑。"

// Teamwork 是和隊友合作的分寸（主管、隊友都適用）：2026-10-21 主管用 21 次工具重查隊友的成果只為了說「方向對」，
// 同一份文案 52 分鐘改了六版、同一份表退回六次。
const Teamwork = "隊友交回的成果，沒有具體疑點就採用，不要自己用工具再查一遍；有疑點只查那一點。" +
	"要隊友修改時，意見一次寫齊，一輪只出一個新版本；能用就採用，小地方自己改。"

// RoomReport 是在群組交辦出去之後，回報到群組的寫法。
const RoomReport = "要使用者決定或提供的事放第一段，一題一段、附選項和你的建議；再用兩三句講整體結果和成品路徑。"

// Room 是群組裡發言的長度。
const Room = "群組裡的發言使用者都看得到：被問就第一句回答，一段一件事、段落之間空一行；" +
	"交棒時一句話寫清楚要對方做什麼，長的資料存成檔案、給路徑。"

// Final 是系統叫 Bot 接著做（自動續做、自動再試）那一輪的回報。原本要「一份完整的最終回報，包含先前已完成的部分」，
// 把回覆越拉越長、重講已經講過的。
const Final = "做完回報：先說好了沒、東西在哪，再補還差什麼；不用重講過程，先前已經講過的結果用一句帶過。"

// Reminder 是守則最後再提醒一次（長的系統提示，結尾的提醒最有用）。
const Reminder = "（回話提醒：回給使用者時像朋友傳訊息，自然口語、句子接得順；長短照「回話長度」，先回應重點，要他決定的事不要埋在最後，不寫過程。）"

// OwnerNoteFor 附在使用者親手打的訊息後面送給引擎（對話裡看不到），style 是回話風格設定。放在訊息旁邊的提醒最有效：
// 2026-10-23 拿掉這裡的數字只留判斷方法，實測簡單問題反而變長（問事實的中位數 201→304 字、「禿頭怎麼辦」389→653 字、
// 「成果在哪兒」89→1000 字），所以常見的幾類照守則寫出長短。研究、規劃和守則同一條：先真的查（2026-10-21「有研究過嗎」）。
func OwnerNoteFor(style string) string {
	s := simple[style]
	if s == "" {
		s = simple["brief"]
	}
	return "\n\n[回覆前提醒：這是使用者本人剛打的訊息。長短照守則的「回話長度」：閒聊一兩句；簡單問題、問事實、問建議，第一句就是答案，" + s +
		"；問進度、問東西在哪，一兩句或給路徑；要你研究、調查、規劃、設計，就先真的查幾個來源，再給結論和骨架，細節放檔案。" + ownerNoteRest
}

// OwnerNote 是預設（簡短）風格的提醒。
var OwnerNote = OwnerNoteFor("brief")

const ownerNoteRest = "" +
	"是交代工作就在這一輪做到完成：說要做的事立刻呼叫工具去做，不要問要不要開始，也不要寫「接下來去做某某」就停下來；" +
	"能自己決定的就做，不要一步一步問「要我…嗎」，做完也不要在結尾問要不要再做別的；要他決定的事回覆長的話放第一段。" +
	"答案會隨時間改變、要精確的數字或出處，或你沒把握的，先上網查；一般常識、意見、閒聊直接回答，不用為了回答去載技能。" +
	"口氣自然，像真人在聊天，照回話風格分段，一律繁體中文。]"
